/* 服务端下发的整屏图片（AI 画图）：铺满整屏、1:1、常驻。
 *
 * 和上面 SetPreviewImage 的区别（各用各的控件，别互相动）：
 *   SetPreviewImage —— preview_image_ 是聊天页中间一块 width_/2 x height_/2 的
 *     预览框（建屏时 :1053），466 的图塞进去只占屏幕四分之一，而且 5 秒自动隐藏。
 *     那是给"预览一张图"用的，铺不出整屏。
 *   SetScreenImage  —— screen_image_ 是整屏大小、居中、压在其它控件之上，
 *     不挂自动隐藏定时器（画完 5 秒自己没了会很莫名其妙），点一下收起来。
 *
 * 放在两个消息风格分支（#if CONFIG_USE_WECHAT_MESSAGE_STYLE）之外：是本类无条件
 * override 的虚函数，声明在 lcd_display.h。WECHAT 风格下 screen_image_ 不会被
 * SetupUI() 建出来，这里就是一句"not initialized"日志，不会崩。
 */
void LcdDisplay::SetScreenImage(std::unique_ptr<LvglImage> image) {
    DisplayLockGuard lock(this);
    if (screen_image_ == nullptr) {
        ESP_LOGE(TAG, "Screen image is not initialized");
        return;
    }

    if (image == nullptr) {
        HideScreenImage();
        return;
    }

    auto img_dsc = image->image_dsc();
    if (img_dsc->header.w <= 0 || img_dsc->header.h <= 0) {
        ESP_LOGW(TAG, "Screen image has invalid dimensions: %ld x %ld", (long)img_dsc->header.w,
                 (long)img_dsc->header.h);
        return;
    }

    screen_image_cached_ = std::move(image);
    lv_image_set_src(screen_image_, screen_image_cached_->image_dsc());

    /* LVGL 的 scale 以 1/256 为单位。服务端是按上报的屏幕尺寸出图的（报 466x466
       就出 466x466），所以这里通常正好是 256 = 1:1 原样铺满；图比屏小时才放大。
       取两个方向的较小值 —— 万一不是正方形，宁可留边也不要撑出屏幕。 */
    const int scale_w = 256 * width_ / (int)img_dsc->header.w;
    const int scale_h = 256 * height_ / (int)img_dsc->header.h;
    const int scale = LV_MIN(scale_w, scale_h);
    lv_image_set_scale(screen_image_, scale);

    lv_obj_remove_flag(screen_image_, LV_OBJ_FLAG_HIDDEN);
    ESP_LOGI(TAG, "Screen image shown: %ldx%ld (scale %d)", (long)img_dsc->header.w,
             (long)img_dsc->header.h, scale);
}

/* 收起整屏图片。看图的两条退出路径（点一下图片 / 停留超时）最后都落到这里，
 * 所以"回到上一屏"这类收尾只写一遍 —— 子类重写 OnScreenImageHidden() 即可。
 *
 * 收尾放在锁内调用：DisplayLockGuard 背后是 lvgl_port_lock()，可重入，子类里再取
 * 一次同一把锁不会自锁（本文件里 SetupUI() 早就在这么嵌套）。 */
void LcdDisplay::HideScreenImage() {
    DisplayLockGuard lock(this);
    if (screen_image_ == nullptr) {
        return;
    }
    const bool was_shown = !lv_obj_has_flag(screen_image_, LV_OBJ_FLAG_HIDDEN);
    lv_obj_add_flag(screen_image_, LV_OBJ_FLAG_HIDDEN);
    screen_image_cached_.reset();
    if (was_shown) {
        OnScreenImageHidden();
    }
}

