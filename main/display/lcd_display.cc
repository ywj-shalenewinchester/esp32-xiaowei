MipiLcdDisplay::MipiLcdDisplay(esp_lcd_panel_io_handle_t panel_io, esp_lcd_panel_handle_t panel,
                               int width, int height, int offset_x, int offset_y, bool mirror_x,
                               bool mirror_y, bool swap_xy)
    : LcdDisplay(panel_io, panel, width, height) {
    ESP_LOGI(TAG, "Initialize LVGL library");
    lv_init();

    ESP_LOGI(TAG, "Initialize LVGL port");
    lvgl_port_cfg_t port_cfg = ESP_LVGL_PORT_INIT_CONFIG();
    /* 这里**故意不绑核**（task_affinity 保持 ESP_LVGL_PORT_INIT_CONFIG 的 -1）。

       曾经绑过 core 1（理由是"相机采集 task 在 core 0，各占一核"），结果滑动待机环
       几次就 Guru Meditation：Core 0 在 gfx_timer_handler 里 Load access fault。

       根因在第三方组件 esp_emote_gfx：gfx_timer.c 整个文件没有任何互斥保护
       （无 mutex / 无临界区），而 gfx_timer_create/delete 会改同一条链表，
       gfx_render_loop_task 又在遍历它。表情没锁，全靠"不会被抢占"侥幸成立：
         - gfx_render  task 优先级 7，绑 core 0（robot_app.c:115）
         - LVGL        task 优先级 4（本文件没设 task_priority，取默认值）
       两者同核时 7 > 4，渲染循环的遍历不可能被 LVGL 侧的表情销毁打断 ——
       不绑核时 LVGL 常落在 core 0，这条优先级排序就是那层意外的保护。
       一旦把 LVGL 摁死在 core 1，两个 task 变成真并发，优先级彻底失效，
       UI 侧 gfx_timer_delete（gfx_anim.c:820，切表情时停动画）就能在 core 0
       遍历到一半时把节点摘掉 → 崩溃。

       ⚠️ 不绑核只是**恢复原来的侥幸**，不是在组件里修好了这个竞争。
       真要根治得给 gfx_timer.c 的链表操作加锁，那是 managed_components 里的
       第三方代码，改它要连带处理升级覆盖的问题，先不动。 */
    lvgl_port_init(&port_cfg);

    ESP_LOGI(TAG, "Adding LCD display");
    const lvgl_port_display_cfg_t disp_cfg = {
        .io_handle = panel_io,
        .panel_handle = panel,
        .control_handle = nullptr,
        /* 这两项在下面的 avoid_tearing + direct_mode 路径里**不生效**：
           esp_lvgl_port_disp.c:369 会在进 direct_mode 判断（:425）之前就把
           buffer_size 覆写成 hres*vres，所以 :425 那句
           `hres*vres == buffer_size` 检查的是覆写后的值、必然成立，
           跟这里填什么无关；:383 的 double_buffer 同理只在 else 分支读。

           ⚠ 反过来说，哪天关掉 avoid_tearing，direct_mode 就必须一起关：
           那时 buffer_size 恢复成 width_*50，:425 会直接以
           "Direct mode must using full buffer!" 挂掉显示初始化。 */
        .buffer_size = static_cast<uint32_t>(width_ * 50),
        .double_buffer = false,
        .hres = static_cast<uint32_t>(width_),
        .vres = static_cast<uint32_t>(height_),
        .monochrome = false,
        /* Rotation values must be same as used in esp_lcd for initial settings of the screen */
        .rotation =
            {
                .swap_xy = swap_xy,
                .mirror_x = mirror_x,
                .mirror_y = mirror_y,
            },
        .flags =
            {
                .buff_dma = true,
                .buff_spiram = false,
                /* ⚠ **必须为 false**，否则开了 avoid_tearing 就起不来。

                   这一项看着像"要不要走软件旋转"，实际语义是"要不要**预留一块旋转缓冲**"：
                   esp_lvgl_port 只要见它为 true，就在 avoid_tearing 路径下额外申请一块
                   buffer_size × 2 字节的缓冲（esp_lvgl_port_disp.c:450-472）。而
                   avoid_tearing 刚把 buffer_size 覆写成整屏 466×466 = 217156 px（:369），
                   于是这次申请是 434KB —— 还因为 buff_dma = true 走内部 RAM，
                   P4 内部 RAM 拿不出这么大一块连续内存，:471 直接 ESP_ERR_NO_MEM：

                       E LVGL: lvgl_port_add_disp_priv(471): Not enough memory for
                       LVGL buffer (rotation buffer) allocation!

                   然后 lvgl_port_add_disp_priv 走 err: 分支（:478）free 掉 disp_ctx 返回
                   NULL，显示初始化半途中止、vsync ISR 却已经在跑，紧接着就是
                   assert failed: spinlock_acquire / Rebooting。

                   原来 `.buffer_size = width_ * 50` 时这块只有 46600 字节，内部 RAM
                   给得起，所以一直没暴露；换成整屏缓冲才炸。

                   而这块缓冲在本板上**一次都不会被写**：旋转缓冲只在
                   current_rotation > LV_DISPLAY_ROTATION_0 时用（:712-731），
                   本板 rotation 是恒等变换（config.h 的 DISPLAY_SWAP_XY / MIRROR_X /
                   MIRROR_Y 全为 false，就在上面 .rotation 里）。关掉它：
                   - 省下 434KB（还省了每次 flush 可能的 lv_draw_sw_rotate）
                   - 代价是 lvgl_port_disp_rotation_update（:763）不再提前返回，
                     boot 时会照 rotation 配置调一次 esp_lcd_panel_swap_xy/mirror(false)
                     —— 那两个值是恒等变换，CO5300 MIPI 这层本来也没实现（板级 lcd.cc
                     有说明），最多打一行 error 日志，不改画面。
                   真需要转屏时，正确做法是走面板 MADCTL 或开 PPA（LVGL_PORT_PPA），
                   而不是打开这个开关去要 434KB 内部 RAM。 */
                .sw_rotate = false,
                /* 和 `.avoid_tearing = true`（在下面 dpi_cfg 里）**必须成对**：
                   avoid_tearing 只负责"拿面板自己的两块帧缓冲当绘制缓冲、在 vsync
                   上换扫描指针"这件事，真正让这套流程跑起来、并且**把 flush 收尾**
                   的是 direct_mode。

                   依据都在 esp_lvgl_port_disp.c 的 flush 回调里：
                   - :744-752 「整屏 draw_bitmap + 等 trans_sem（= 等 vsync）」整段
                     包在 `flags.direct_mode || flags.full_refresh` 条件内；
                   - :757-759 的 `lv_disp_flush_ready()` 在**同一个**条件内。

                   少这一项就会：每帧走 :754 那条按区域 draw_bitmap 的 else 分支，并且
                   lv_disp_flush_ready() 一次都不执行 —— LVGL 的 disp->flushing 永远
                   停在 1，下一次刷新直接卡死在 wait_for_flushing（lv_refr.c:1451/1458）
                   里空转。症状是 UI 起来后十几秒冻住，task_wdt 报 IDLE1 超时、
                   CPU1 停在 taskLVGL。

                   ⚠ 别指望 avoid_tearing 注册的那个 vsync 回调来补：
                   on_refresh_done → lvgl_port_flush_dpi_vsync_ready_callback(:523)
                   **只 give 信号量、不调 flush_ready**。

                   direct_mode 的隐含要求是"缓冲必须整屏"（:425 那句断言），由
                   avoid_tearing 在 :369 覆写 buffer_size 来满足 —— 见上面
                   .buffer_size 那段的说明。

                   ⚠ 这两项的**书写顺序也不能调换**：头文件里 sw_rotate 声明在
                   direct_mode 之前（esp_lvgl_port_disp.h:64-73），C++ 的指定初始化器
                   顺序与声明不符是硬错误。 */
                .direct_mode = false,
            },
    };

    /* avoid_tearing = true：不用 LVGL 自己那块绘制缓冲，改用 DPI 面板的两块
       帧缓冲（配套改板级 lcd.cc 的 num_fbs = 2，缺一不可），画完在 vsync 上换
       扫描指针 —— 这是这条显示链路上唯一能真正消除撕裂的做法。

       ⚠ 它不只是"省一次拷贝"，还把**刷新的节奏源换掉了**：flush 里会
       xSemaphoreTake(trans_sem, portMAX_DELAY)（esp_lvgl_port_disp.c:751）一直
       阻塞到面板发 on_refresh_done。从现在起帧率由**面板 vsync**（59.94Hz）
       决定，而不是由下面那个 LVGL 刷新定时器决定 —— 所以那个周期必须跟着改，
       否则两套互不同步的节奏会互相打架，见下面那段。 */
    /* ⚠ avoid_tearing 关掉了（原来是 true）。上面那整段"画完在 vsync 上换扫描
       指针"的推理**在这块板子上不成立** —— 依据是把已编译的 IDF 驱动反汇编
       （build/esp-idf/esp_lcd/CMakeFiles/__idf_esp_lcd.dir/dsi/esp_lcd_panel_dpi.c.obj）：

         · 面板扫哪块缓冲由 esp_lcd_panel_dpi_t 的 cur_fb_index（结构体偏移 53）决定，
           DSI 的 GDMA 链路表就取 panel[100 + cur*4]（mipi_dsi_dma_trans_done_cb）。
         · 整个 .obj 里**只有两处**写这个 53：
             - dpi_panel_init: `sb zero,53` —— 上电置 0（于是永远扫 fbs[0]）;
             - dpi_panel_draw_bitmap: `sb s2,53`，而它只在
               「color_data 是本面板的帧缓冲之**一**」且 **panel[112] == NULL**（同步
               CPU 拷贝分支）时才会执行到。
         · panel[112] 就是 DMA2D 句柄，由板级 lcd.cc 的 use_dma2d = true 装上。
           该分支（.L32）走 xQueueSemaphoreTake(panel[116], 0) 后就 esp_async_fbcpy
           直接返回，**从不碰 53**；失败时只打一句
           "previous draw operation is not finished" 并返回 ESP_ERR_TIMEOUT。
           async_fbcpy_done_cb 也只 give 信号量 + 回调 on_color_trans_done，同样不碰 53。

       合起来：use_dma2d 一开，cur_fb_index 永远停在 0，**面板只扫 fbs[0]**，
       fbs[1] 一次都不会上屏。而 avoid_tearing 恰恰把 LVGL 的两块绘制缓冲换成
       了 fbs[0]/fbs[1]（DIRECT 模式），于是隔帧就出现：

         帧A：LVGL 把脏区**直接画进正在被扫描的 fbs[0]**
              （本工程整屏重绘实测 22~41ms = 面板 1.3~2.5 帧）→ 画面被逐块覆写、
              撕裂、闪烁；draw_bitmap 再把自己拷给自己一遍（434KB 白扔）；
         帧B：画进 fbs[1]（**屏上根本看不见这块**），靠 draw_bitmap 的一次
              DMA2D 整屏 blit 拷回 fbs[0]，同样不与扫描同步 → 又一条滚动撕裂带。

       这正是"按住滑动时屏一直闪、非常不稳定、撕裂明显"；静止时两帧内容相同，
       写进去的字节一样，所以看不出来。主菜单只有局部小幅位移，也轻得多。

       修法：让 LVGL 画进它**自己**的缓冲（avoid_tearing = false，与 direct_mode
       必须同时为 false —— direct_mode 会去 take 那个只在 avoid_tearing 分支里
       创建的 trans_sem，避免空句柄），每次刷新就退化成 :754 那条按区域
       draw_bitmap → DMA2D 把这一段**原子地**blit 进 fbs[0]，由
       async_fbcpy_done_cb → on_color_trans_done → lv_disp_flush_ready 收尾。
       屏幕不再有"渲染直接写进在扫的缓冲"这种 40ms 级的连续覆写。

       剩下的残余：blit 仍未对齐 vsync，快速滑动时边界上会有一条细撕裂带。
       要再进一步就得让 present 卡在 vsync 上做（on_refresh_done 那套），
       属于下一步，先看这一改的实际效果。 */
    const lvgl_port_display_dsi_cfg_t dpi_cfg = {.flags = {
                                                     .avoid_tearing = false,
                                                 }};
    display_ = lvgl_port_add_disp_dsi(&disp_cfg, &dpi_cfg);
    if (display_ == nullptr) {
        ESP_LOGE(TAG, "Failed to add display");
        return;
    }

    if (offset_x != 0 || offset_y != 0) {
        lv_display_set_offset(display_, offset_x, offset_y);
    }

    /* LVGL 的刷新定时器周期取自编译期的 LV_DEF_REFR_PERIOD（当前 sdkconfig 是 16ms），
       esp_lvgl_port 不暴露这个开关，只能拿到句柄后改。

       这个周期是"两次刷新**开始**之间的最小间隔"，注意两点：
         - 定时器在每次刷新开始时被 lv_timer_pause()，只有 LV_EVENT_REFR_REQUEST
           （真有区域被 invalidate 了）才 lv_timer_resume()
           （lv_refr.c:373 / lv_display.c:1556）→ 没东西要画时它一直是 pause 的，
           不存在空转轮询（前提 LV_USE_PERF_MONITOR 为 0，本工程未开启）；
         - last_run 是在**进回调之前**打上的（lv_timer.c:348）：
               timer->last_run = lv_tick_get();
               timer->timer_cb(timer);   // 刷新回调在这里阻塞到 flush_ready
           所以回调阻塞多久都不推迟下一次触发时刻。
       合起来：实际帧间隔 = max(period, 一次刷新真正花的时间)。

       ⚠ 上面这套"必须是 1"的推理，前提是 avoid_tearing 让 flush 阻塞在 vsync 上；
       那个前提已经关掉了（见下面 dpi_cfg）。现在 flush 只等到一次区域 blit 完成
       （DMA2D 完成中断，几十~几百 us），整条链路上**没有任何 vsync 握手**，这个
       周期就重新变成唯一的节奏源。此时留 1ms 只会让 LVGL 一有空就重绘，把 CPU 和
       PSRAM 全占满，而帧率并不会更高（一帧真正花多久由绘制量决定，实测 22~41ms）。
       回到 16ms，与面板的 16.68ms 大致对齐，省下的总线留给渲染本身。

       （下面这段是 avoid_tearing 时期的记录，保留作对照 —— 那时 flush 会阻塞到
       下一颗 vsync，节奏源在面板上，所以周期必须是 1ms，否则两套节奏互抢、
       帧间隔在 16.7 / 33.3ms 之间来回抖。现在 flush 不再等 vsync，前提已不成立。）

       16ms 是当初**没有** avoid_tearing 时定的：那时没有 vsync 握手，这个周期
       就是唯一的节奏源，16ms → 62.5fps，正好。

       现在 flush 自己会阻塞到下一颗 vsync（16.68ms），节奏源已经换成面板了。
       这里再留 16ms 就是两套互不同步的节奏抢：
         - 定时器每 16ms 催一次刷新，
         - 而 vsync 每 16.68ms 才来一颗，
       于是同一帧里 flush 有时只等 0.7ms、有时要整整多等一颗 vsync，帧间隔在
       16.7 / 33.3ms 之间来回跳 —— 平均远不到 60，而且是**抖**的。
       抖比平均帧率更刺眼，看上去就是"动画不流畅"。

       改成 1ms：刷新在 flush_ready（恰好落在某颗 vsync 上）之后几乎立刻重启，
       每帧就恰好等一颗 vsync → 帧间隔稳定 16.68ms，锁死面板的 59.94Hz，不抖。
       前提是单帧工作量（sync 拷贝 + 绘制 + 整屏 flush 拷贝）本身小于一帧，
       超了就会规律地掉到 30fps —— FPS 叠加层里的 "UI n" 就是实测值，用它验证。 */
    lv_timer_t* refr_timer = lv_display_get_refr_timer(display_);
    if (refr_timer != nullptr) {
        lv_timer_set_period(refr_timer, 16);
    } else {
        ESP_LOGW(TAG, "no refresh timer on display; LVGL frame rate stays capped by LV_DEF_REFR_PERIOD");
    }
}

